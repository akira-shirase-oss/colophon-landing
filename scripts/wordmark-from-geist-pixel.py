"""Builds the footer wordmark from Geist Pixel's own glyphs, so the pixel type is one family:

    python3 scripts/wordmark-from-geist-pixel.py   (needs fontTools and brotli: pip install fonttools brotli)

Geist Pixel draws every glyph as separate square cells on a 38-unit grid. This reads the cells of "Colophon"
from the shipped public/fonts/geist-pixel-latin.woff2, lays the letters out by their own advances, merges
each row's cells into runs and writes src/components/ui/wordmark-cells.ts: one SVG path in cell units
(y down from the cap top) plus the size of the grid. The hairline gaps between cells come from a mask in
BrandWordmark.astro, so the path stays small. Re-run it after changing the font file, and commit the output.
"""
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.recordingPen import RecordingPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
WORD = "Colophon"
CELL = 38

font = TTFont(ROOT / "public/fonts/geist-pixel-latin.woff2")
glyphs = font.getGlyphSet()
cmap = font.getBestCmap()
cap_top = round(font["OS/2"].sCapHeight / CELL)  # the row just above the cap height

cells = set()
pen_x = 0
for ch in WORD:
    name = cmap[ord(ch)]
    rec = RecordingPen()
    glyphs[name].draw(rec)
    contour = []
    for op, args in rec.value:
        if op == "moveTo":
            contour = [args[0]]
        elif op in ("lineTo", "qCurveTo", "curveTo"):
            contour.extend(args)
        elif op in ("closePath", "endPath"):
            xs = [p[0] for p in contour]
            ys = [p[1] for p in contour]
            col = round(min(xs) / CELL) + pen_x
            row = cap_top - round(max(ys) / CELL)
            if round((max(xs) - min(xs)) / CELL) != 1 or round((max(ys) - min(ys)) / CELL) != 1:
                raise SystemExit(f"{ch}: a contour is not one cell; the font is not the pixel instance this expects")
            cells.add((col, row))
    pen_x += round(glyphs[name].width / CELL)

min_row = min(r for _, r in cells)
max_row = max(r for _, r in cells)
min_col = min(c for c, _ in cells)
width = max(c for c, _ in cells) - min_col + 1
height = max_row - min_row + 1
parts = []
for row in range(min_row, max_row + 1):
    cols = sorted(c - min_col for c, r in cells if r == row)
    run_start = None
    for i, c in enumerate(cols):
        if run_start is None:
            run_start = c
        if i + 1 == len(cols) or cols[i + 1] != c + 1:
            parts.append(f"M{run_start} {row - min_row}h{c - run_start + 1}v1h-{c - run_start + 1}z")
            run_start = None

out = ROOT / "src/components/ui/wordmark-cells.ts"
out.write_text(
    "// Generated by scripts/wordmark-from-geist-pixel.py from public/fonts/geist-pixel-latin.woff2. Do not edit.\n"
    f"// \"{WORD}\" in Geist Pixel: {len(cells)} cells on a {width} x {height} grid; row 0 is the cap top.\n"
    "export const wordmark = {\n"
    f"  width: {width},\n"
    f"  height: {height},\n"
    f"  capRows: {cap_top - min_row + 1},\n"
    f"  path: '{''.join(parts)}',\n"
    "}\n"
)
print(f"{out.relative_to(ROOT)}: {len(cells)} cells, {width} x {height}, path {len(''.join(parts))} characters")
